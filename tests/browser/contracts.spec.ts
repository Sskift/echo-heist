test('an active contract cannot override explicit demo or training navigation',async({page})=>{
  const ids=MISSIONS.filter(m=>m.chapter!=='机制试验').map(m=>m.id);
  const save=new Campaign({version:1,selected:'C0-1',runs:Object.fromEntries(ids.map(id=>[id,[]])),completed:ids}).export();
  await page.addInitScript(save=>{
    if(!localStorage.getItem('echo-heist-campaign-v1'))localStorage.setItem('echo-heist-campaign-v1',JSON.stringify(save));
    if(!localStorage.getItem('echo-heist-contracts-v1'))localStorage.setItem('echo-heist-contracts-v1',JSON.stringify({version:1,rotation:0,active:'station-platform',inContracts:true,scores:{}}));
  },save);
  await page.goto('/?demo=station-transfer');await advance(page);
  await expect(page.locator('#chapter-label')).toContainText('独立试玩');
  await expect(page.locator('#contracts-button')).not.toBeVisible();
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('echo-heist-campaign-v1')!))).toEqual(save);
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('echo-heist-contracts-v1')!).inContracts)).toBe(true);
  await page.goto('/');await advance(page);
  await expect(page.locator('#mission-title')).toHaveText('送件的人，留下开门');
  await page.goto('/?mode=training');await advance(page);
  await expect(page.locator('#mission-title')).toHaveText('不在场证明');
  await expect(page.locator('#contract-strip')).not.toBeVisible();
  const state=await page.evaluate(()=>JSON.parse(localStorage.getItem('echo-heist-contracts-v1')!));
  expect(state.inContracts).toBe(false);expect(state.active).toBe('station-platform');
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('echo-heist-campaign-v1')!))).toEqual(save);
});
