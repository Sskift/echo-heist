test('contract saves cannot bypass main completion, and the locked board pauses gameplay',async({page})=>{
  await page.addInitScript(()=>localStorage.setItem('echo-heist-contracts-v1',JSON.stringify({version:1,rotation:1,active:'station-window',inContracts:true,scores:{}})));
  await page.goto('/'); await advance(page); await page.locator('#story-skip').click();
  await page.locator('#overlay-action').click(); await advance(page,15);
  const before=await page.locator('#seconds').textContent();
  await page.locator('#contracts-button').click(); await move(page,'d',60);
  await expect(page.locator('#seconds')).toHaveText(before!);
  await expect(page.locator('#contracts-intro')).toContainText('完成八章主线后');
  await expect(page.locator('[data-contract]')).toHaveCount(0);
  await expect(page.locator('#contracts-refresh')).toBeDisabled();
  await page.locator('#contracts-close').click(); await advance(page);
  await expect(page.locator('#mission-title')).toHaveText('一道需要两个人的门');
  await expect(page.locator('#record-label')).toHaveText('PAUSED');
});

